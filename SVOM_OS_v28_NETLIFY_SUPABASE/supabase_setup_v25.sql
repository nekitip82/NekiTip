create table if not exists public.svom_os_state (
  key text primary key,
  value jsonb,
  updated_by text,
  updated_at timestamptz not null default now()
);

alter table public.svom_os_state enable row level security;
drop policy if exists "svom_os_state_all_anon" on public.svom_os_state;
create policy "svom_os_state_all_anon"
on public.svom_os_state for all to anon
using (true) with check (true);

grant select, insert, update, delete on public.svom_os_state to anon;

-- Zaseben bucket za priponke. Dostop je dovoljen aplikaciji prek publishable/anon ključa.
insert into storage.buckets (id,name,public)
values ('svom-os-attachments','svom-os-attachments',false)
on conflict (id) do update set public=false;

drop policy if exists "svom_os_storage_select_anon" on storage.objects;
create policy "svom_os_storage_select_anon"
on storage.objects for select to anon
using (bucket_id='svom-os-attachments');

drop policy if exists "svom_os_storage_insert_anon" on storage.objects;
create policy "svom_os_storage_insert_anon"
on storage.objects for insert to anon
with check (bucket_id='svom-os-attachments');

drop policy if exists "svom_os_storage_update_anon" on storage.objects;
create policy "svom_os_storage_update_anon"
on storage.objects for update to anon
using (bucket_id='svom-os-attachments')
with check (bucket_id='svom-os-attachments');

drop policy if exists "svom_os_storage_delete_anon" on storage.objects;
create policy "svom_os_storage_delete_anon"
on storage.objects for delete to anon
using (bucket_id='svom-os-attachments');
