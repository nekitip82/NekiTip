create extension if not exists pgcrypto;

-- 1. OSEBE
create table if not exists public.svom_users (
  id bigint generated by default as identity primary key,
  code text not null unique,
  active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

-- 2. VRSTE DELA
create table if not exists public.svom_work_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  color text not null default 'gray'
    check (color in ('red','yellow','green','gray')),
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

-- 3. KATEGORIJE
create table if not exists public.svom_categories (
  id bigint generated by default as identity primary key,
  work_type_id bigint not null references public.svom_work_types(id) on delete cascade,
  name text not null,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  unique(work_type_id, name)
);

-- 4. PODKATEGORIJE
create table if not exists public.svom_subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.svom_categories(id) on delete cascade,
  name text not null,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  unique(category_id, name)
);

-- 5. LOKACIJE
create table if not exists public.svom_locations (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 100,
  created_at timestamptz not null default now()
);

-- 6. DELOVODNIK
create table if not exists public.svom_worklog (
  id uuid primary key default gen_random_uuid(),
  work_date date not null,
  work_type text not null,
  category text,
  subcategory text,
  location text,
  leader text,
  crew text[] not null default '{}',
  description text not null default '',
  materials text,
  notes text,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists svom_worklog_work_date_idx
  on public.svom_worklog(work_date desc);

-- updated_at trigger
create or replace function public.svom_set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists svom_worklog_set_updated_at on public.svom_worklog;
create trigger svom_worklog_set_updated_at
before update on public.svom_worklog
for each row execute function public.svom_set_updated_at();

