on public.svom_locations for all to anon
using (true) with check (true);

drop policy if exists "svom_worklog_all_anon" on public.svom_worklog;
create policy "svom_worklog_all_anon"
on public.svom_worklog for all to anon
using (true) with check (true);

grant usage on schema public to anon;
grant select, insert, update, delete on
